"""Enforce per-module line coverage for security- and tenant-sensitive API routers."""

from __future__ import annotations

import sys
from pathlib import Path
from xml.etree import ElementTree

MINIMUM_COVERAGE = 0.80

CRITICAL_ROUTERS = (
    "adapters/api/routers/auth.py",
    "adapters/api/routers/leader_unavailabilities.py",
    "adapters/api/routers/planning_series.py",
    "adapters/api/routers/system.py",
)


def check_critical_coverage(xml_path: Path) -> list[str]:
    """Return failures for missing, ambiguous or under-covered router modules."""
    root = ElementTree.parse(xml_path).getroot()
    classes = root.findall(".//class")
    failures: list[str] = []
    for expected in CRITICAL_ROUTERS:
        matches = [
            item for item in classes
            if item.get("filename", "").replace("\\", "/").endswith(expected)
        ]
        if len(matches) != 1:
            failures.append(
                f"{expected}: expected exactly one file in coverage.xml, found {len(matches)}"
            )
            continue
        rate = float(matches[0].get("line-rate", "0"))
        print(f"{expected}: {rate:.1%} (minimum {MINIMUM_COVERAGE:.0%})")
        if rate < MINIMUM_COVERAGE:
            failures.append(f"{expected}: {rate:.1%} below {MINIMUM_COVERAGE:.0%}")
    return failures


def main() -> int:
    """Check the unit-test coverage XML generated by pytest-cov."""
    xml_path = Path(sys.argv[1] if len(sys.argv) > 1 else "coverage.xml")
    failures = check_critical_coverage(xml_path)
    for failure in failures:
        print(f"::error::{failure}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
